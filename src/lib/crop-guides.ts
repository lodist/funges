/**
 * How to look after each crop once it is in, in numbers and levels; the crop
 * sheet says them in words, and its texts are under `grow.<id>` in the huerta
 * namespace. From the RHS and university extension guides each crop's
 * `grow.<id>.source` names.
 */

export interface CropGuide {
  water: 'high' | 'medium' | 'low';
  feed: 'high' | 'medium' | 'low';
  /** The soil pH it grows best in. */
  ph: [number, number];
  /** Plants per person: to eat fresh, and to keep (stored, frozen) too;
   *  absent where no guide gives a figure (herbs, flowers, cover crops). */
  perPerson?: { fresh: [number, number]; keep?: [number, number] };
  /** The smallest pot it grows in, cm across; null: not for pots. */
  pot: number | null;
}

